import { expect, test } from '@playwright/test'
import { BACKEND_URL, FRONTEND_URL, openGameEndControls } from './fixtures'
import { authenticateSolo } from './helpers/standard-solo-acceptance'

test('multiplayer end proposal survives refresh, can be rejected, and ends only after the other player agrees', async ({ browser, request }, testInfo) => {
  const hostContext = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const guestContext = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    const suffix = Date.now().toString(36)
    await authenticateSolo(hostContext, request, `end_host_${suffix}`)
    await authenticateSolo(guestContext, request, `end_guest_${suffix}`)
    const host = await hostContext.newPage()
    const guest = await guestContext.newPage()
    await host.goto(`${FRONTEND_URL}/?transport=ws&maxPlayers=2&draftMode=simultaneous&draftPoolSize=7`)
    const roomId = await host.locator('.ws-invite-roomid strong').textContent()
    expect(roomId).toBeTruthy()
    await guest.goto(`${FRONTEND_URL}/?room=${roomId}`)
    await guest.getByRole('button', { name: /Confirm color and start/i }).click()
    host.on('dialog', dialog => dialog.accept())
    const hostControls = await openGameEndControls(host)
    await hostControls.getByRole('button', { name: 'Propose ending the game', exact: true }).click()
    let guestControls = await openGameEndControls(guest)
    await expect(guestControls).toContainText('Agreed: 1/2')
    await guest.reload()
    guestControls = await openGameEndControls(guest)
    await expect(guestControls).toContainText('Agreed: 1/2')
    await guestControls.getByRole('button', { name: 'Reject', exact: true }).click()
    await expect((await openGameEndControls(host)).getByRole('button', { name: 'Propose ending the game', exact: true })).toBeEnabled()
    await (await openGameEndControls(host)).getByRole('button', { name: 'Propose ending the game', exact: true }).click()
    guestControls = await openGameEndControls(guest)
    await expect(guestControls).toContainText('Agreed: 1/2')
    await guest.screenshot({ path: testInfo.outputPath('mobile-end-proposal.png'), fullPage: true })
    expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const before = await (await request.get(`${BACKEND_URL}/api/v1/game-contexts/${roomId}`)).json()
    expect(before.lifecycle).not.toBe('terminated')
    await (await openGameEndControls(guest)).getByRole('button', { name: 'Agree', exact: true }).click()
    await expect(host.getByRole('heading', { name: 'Ended by agreement', exact: true })).toBeVisible()
    await expect(guest.getByRole('heading', { name: 'Ended by agreement', exact: true })).toBeVisible()
    const ended = await (await request.get(`${BACKEND_URL}/api/v1/game-contexts/${roomId}`)).json()
    expect(ended).toMatchObject({ ok: true, lifecycle: 'terminated', termination: { reason: 'agreement', players: expect.any(Array) } })
    expect(ended.termination.players).toHaveLength(2)
    expect(ended).not.toHaveProperty('result')
    const manifest = await (await request.get(`${BACKEND_URL}/api/v1/replays/${roomId}/manifest`)).json()
    expect(manifest.ok).toBe(true)
    expect(manifest.participants).toHaveLength(2)
    await host.goto(FRONTEND_URL)
    await expect(host.getByRole('heading', { name: 'Recent ended games' })).toBeVisible()
    await expect(host.getByText('Ended by agreement', { exact: true })).toBeVisible()
  } finally { await hostContext.close(); await guestContext.close() }
})

test('solo can end during choose-seven setup after one confirmation', async ({ browser, request }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  try {
    await authenticateSolo(context, request, `end_solo_${Date.now().toString(36)}`)
    const page = await context.newPage()
    await page.goto(FRONTEND_URL)
    await page.getByRole('button', { name: 'Solo game', exact: true }).click()
    const setup = page.getByRole('dialog', { name: 'Start a solo game' })
    await setup.getByRole('radio', { name: /Choose 7 from 10/ }).check()
    await setup.getByRole('button', { name: 'Start solo game', exact: true }).click()
    await expect(page).toHaveURL(/\?room=[^&]+/)
    const roomId = new URL(page.url()).searchParams.get('room')
    page.once('dialog', dialog => dialog.accept())
    await (await openGameEndControls(page)).getByRole('button', { name: 'Propose ending the game', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Ended by agreement', exact: true })).toBeVisible()
    expect(await (await request.get(`${BACKEND_URL}/api/v1/game-contexts/${roomId}`)).json())
      .toMatchObject({ lifecycle: 'terminated', termination: { reason: 'solo_confirmation' } })
  } finally { await context.close() }
})

