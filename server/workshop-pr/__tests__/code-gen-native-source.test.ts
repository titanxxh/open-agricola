import { describe, expect, it } from 'vitest'
import ts from 'typescript'
import { generateCardSourceFile, generatePrFiles } from '../code-gen'
import { WOODPILE_SOURCE } from '../../../shared/custom-code/__tests__/native-card-fixture'

// A native draft carries its own translations; pull requests ship them as a separate patch.
const source = WOODPILE_SOURCE.replace("cost: { wood: 1 } }", "cost: { wood: 1 }, locales: { zh: { name: '柴堆钩', desc: ['使用捕鱼时额外获得 1 <WOOD>。'] } } }")
const wcard = {
  id: 'wc-native', card_id: 'CUSTOM_WoodpileHook', card_type: 'minor',
  card_json: JSON.stringify({ name: 'Woodpile Hook', locales: { zh: { name: '柴堆钩' } } }),
  effect_code: source, art_url: null as string | null, author_name: 'alice', description: 'Fishing bonus',
}

describe('PR generation from a native Card Source draft (ADR 0052)', () => {
  it('keeps the module, drops its translations, sets the art and adds the registry export', () => {
    const file = generateCardSourceFile(wcard, { githubLogin: 'alice-gh', iso: '2026-11-20', artUrl: '/card-art/community/CUSTOM_WoodpileHook.png' })
    expect(file).toContain("import { defineMinorCard } from '../card-source'")
    expect(file).toContain("actionSpaces: ['fishing']")
    expect(file).not.toContain('locales')
    expect(file).toContain('artUrl: "/card-art/community/CUSTOM_WoodpileHook.png"')
    expect(file).toContain('export const CUSTOM_WoodpileHook_impl = CUSTOM_WoodpileHook.impl')
    const syntax = ts.transpileModule(file, { reportDiagnostics: true, compilerOptions: { module: ts.ModuleKind.ESNext } })
    expect(syntax.diagnostics ?? []).toEqual([])
  })

  it('registers the card and its catalog entry like a legacy draft', async () => {
    const files = await generatePrFiles({
      wcard, github_login: 'alice-gh', pr_number: 0, art_data: null,
      upstream_register_all: `// GENERATED ...
import './catalog'

import { A001_impl } from './A/A001_X'

export const ALL_CARD_IMPLS: Readonly<Record<string, CardImpl>> = {
  'A1': A001_impl,
}

export type AllCardImpls = typeof ALL_CARD_IMPLS
`,
      upstream_catalog_generated: `// GENERATED by scripts/generate-register-all.ts. Do not edit by hand.
import type { CardDefinition } from '../contract/cards'

type GeneratedCatalogCardDefinition = CardDefinition & {
  kind: 'minor' | 'occupation' | 'playerAction'
}

export const catalogCardDefinitions: readonly GeneratedCatalogCardDefinition[] = [
  {
    "id": "A001_Source",
    "name": "Source",
    "deck": "A",
    "number": 1,
    "desc": [],
    "kind": "minor"
  },
]
`,
      upstream_community_md: '# CC\n<!-- community-card-entries:begin -->\n| ID |\n<!-- community-card-entries:end -->\n',
    })
    expect(files.find(file => file.path === 'shared/cards/register-all.ts')?.content).toContain("import { CUSTOM_WoodpileHook } from './community/CUSTOM_WoodpileHook'")
    expect(files.find(file => file.path === 'shared/cards/catalog.generated.ts')?.content).toContain('"id": "CUSTOM_WoodpileHook"')
  })
})
