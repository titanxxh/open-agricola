import { describe, expect, it } from 'vitest'
import { assertRejectedUnchanged } from './_helpers/session-assertions'
import { partnerTable, restorePartnerTable } from './_helpers/partner-build-fixture'

describe('Partner Build stables',()=>{
  it('keeps the builder command and payment while placing on the selected teammate farm',()=>{
    const session=partnerTable(state=>{state.players[0]!.resources.wood=3})
    const offered=session.takeAction(0,'farm-expansion')
    expect(offered.ok,offered.error).toBe(true)
    expect(offered.interaction).toMatchObject({stateId:'wait',playerIndex:0,request:{kind:'choice',defaultValue:'target-farm:p1',options:[{value:'target-farm:p1'},{value:'target-farm:p3'}]}})
    const chosen=session.resolveChoice(0,'target-farm:p3')
    expect(chosen.ok,chosen.error).toBe(true)
    expect(chosen.interaction).toMatchObject({stateId:'wait',playerIndex:0,request:{kind:'farm-select',farmOwnerPlayerId:'p3',farm:{farmType:'stable'}}})
    const built=session.commitSelectionChoice(0,{stables:[{row:0,col:2}]})
    expect(built.ok,built.error).toBe(true)
    expect(built.state.players[0]!.resources.wood).toBe(0)
    expect(built.state.players[0]!.stableTiles).toEqual([])
    expect(built.state.players[2]!.stableTiles).toEqual([{row:0,col:2}])
    expect(built.state.players[2]!.resources.wood).toBe(0)
    expect(built.scores?.find(score=>score.playerId==='p3')?.categories.find(category=>category.key==='empty')?.total).toBe(-12)
    expect(built.scores?.find(score=>score.playerId==='p1')?.categories.find(category=>category.key==='empty')?.total).toBe(-13)
    expect(built.state.events).toContainEqual(expect.objectContaining({type:'farm.stableBuilt',actorPlayerId:'p1',targetPlayerId:'p3'}))
    expect(built.state.log).toContainEqual(expect.objectContaining({key:'log.partnerStablesBuilt',playerId:'p1',playerRefs:{owner:'p3'}}))
  })
  it('offers only a teammate with supply and rejects opponents or the wrong command owner unchanged',()=>{
    const session=partnerTable(state=>{state.players[0]!.resources.wood=3;state.players[0]!.stableTiles=[1,2,3,4].map(col=>({row:0,col}))})
    expect(session.takeAction(0,'farm-expansion').interaction).toMatchObject({stateId:'wait',request:{kind:'choice',options:[{value:'target-farm:p3'}]}})
    assertRejectedUnchanged(session,()=>session.resolveChoice(0,'target-farm:p2'))
    assertRejectedUnchanged(session,()=>session.resolveChoice(2,'target-farm:p3'))
    expect(session.resolveChoice(0,'target-farm:p3').ok).toBe(true)
    const built=session.commitSelectionChoice(0,{stables:[{row:0,col:2}]})
    expect(built.ok,built.error).toBe(true)
    expect(built.state.players[0]!.stableTiles).toHaveLength(4)
    expect(built.state.players[2]!.stableTiles).toHaveLength(1)
  })
  it('restores the target choice and locked placement, then undoes and redoes a partner stable once',()=>{
    const session=partnerTable(state=>{state.players[0]!.resources.wood=3})
    expect(session.takeAction(0,'farm-expansion').ok).toBe(true)
    const choice=restorePartnerTable(session)
    expect(choice.resolveChoice(0,'target-farm:p3').ok).toBe(true)
    const placement=restorePartnerTable(choice)
    expect(placement.getState().interaction).toMatchObject({stateId:'wait',playerIndex:0,request:{farmOwnerPlayerId:'p3'}})
    assertRejectedUnchanged(placement,()=>placement.resolveChoice(0,'target-farm:p1'))
    assertRejectedUnchanged(placement,()=>placement.commitSelectionChoice(2,{stables:[{row:0,col:2}]}))
    expect(placement.commitSelectionChoice(0,{stables:[{row:0,col:2}]}).ok).toBe(true)
    const undone=placement.undoAction()
    expect(undone.ok,undone.error).toBe(true)
    expect(undone.state.players[0]!.resources.wood).toBe(3)
    expect(undone.state.players[2]!.stableTiles).toEqual([])
    expect(undone.state.log.some(entry=>entry.key==='log.partnerStablesBuilt')).toBe(false)
    expect(placement.takeAction(0,'farm-expansion').ok).toBe(true)
    expect(placement.resolveChoice(0,'target-farm:p3').ok).toBe(true)
    const repeated=placement.commitSelectionChoice(0,{stables:[{row:0,col:2}]})
    expect(repeated.state.players[0]!.resources.wood).toBe(0)
    expect(repeated.state.players[2]!.stableTiles).toHaveLength(1)
    expect(repeated.state.log.filter(entry=>entry.key==='log.partnerStablesBuilt')).toHaveLength(1)
  })
  it('keeps the ordinary two-player stable price and own-farm flow',()=>{
    const session=partnerTable(state=>{state.players[0]!.resources.wood=2},{ordinary:true})
    const started=session.takeAction(0,'farm-expansion')
    expect(started.interaction).toMatchObject({stateId:'wait',request:{kind:'farm-select',farm:{farmType:'stable'}}})
    const built=session.commitSelectionChoice(0,{stables:[{row:0,col:2}]})
    expect(built.ok,built.error).toBe(true)
    expect(built.state.players[0]!.resources.wood).toBe(0)
    expect(built.state.players[0]!.stableTiles).toEqual([{row:0,col:2}])
    expect(built.state.players[1]!.stableTiles).toEqual([])
    expect(built.state.log.some(entry=>entry.key==='log.partnerStablesBuilt')).toBe(false)
  })

})

it('Carpenter Apprentice counts the target third and fourth stable while charging the builder', () => {
  const session = partnerTable(state => {
    state.players[0]!.occupationPlayed = ['C088_CarpentersApprentice']
    state.players[0]!.resources.wood = 4
    state.players[2]!.stableTiles = [{row:0,col:0},{row:0,col:1}]
  })
  expect(session.takeAction(0, 'farm-expansion').ok).toBe(true)
  expect(session.resolveChoice(0, 'target-farm:p3').ok).toBe(true)
  const built = session.commitSelectionChoice(0, {stables:[{row:0,col:2},{row:0,col:3}]})
  expect(built.ok,built.error).toBe(true)
  expect(built.state.players[0]!.resources.wood).toBe(0)
  expect(built.state.players[0]!.stableTiles).toEqual([])
  expect(built.state.players[2]!.stableTiles).toHaveLength(4)
  expect(built.state.events).toContainEqual(expect.objectContaining({type:'resource.paid',actorPlayerId:'p1',resources:{wood:4},paymentFor:'stables'}))
})

it.each(['team','multihand'] as const)('allows only the builder team farms in a six-player %s game',mode=>{
  const session=partnerTable(state=>{state.players[0]!.resources.wood=3},{playerCount:6,teamConfig:{mode,seatsPerTeam:3,seating:'separated',scoring:'sum',teammateVisibility:'private',cooperationRules:true}})
  const offered=session.takeAction(0,'farm-expansion')
  expect(offered.interaction).toMatchObject({stateId:'wait',request:{kind:'choice',options:[{value:'target-farm:p1'},{value:'target-farm:p3'},{value:'target-farm:p5'}]}})
  assertRejectedUnchanged(session,()=>session.resolveChoice(0,'target-farm:p4'))
  const resumed=restorePartnerTable(session)
  expect(resumed.resolveChoice(0,'target-farm:p5').ok).toBe(true)
  const built=resumed.commitSelectionChoice(0,{stables:[{row:0,col:2}]})
  expect(built.ok,built.error).toBe(true)
  expect(built.state.players[0]!.resources.wood).toBe(0)
  expect(built.state.players[4]!.stableTiles).toEqual([{row:0,col:2}])
  expect(built.state.players[2]!.stableTiles).toEqual([])
})

